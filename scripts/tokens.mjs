// Writes the brand values into the app from the brand pack's token file.   npm run tokens
// Source: brand/ef-tokens.json (Executive Frame brand pack, copied in unchanged; replace it when a new pack arrives).
// Writes: 1. the generated block of public/assets/css/tokens.css: palette, the 2 themes, application colours,
//            spacing, radius and motion. The app's own type sizes and control sizes stay hand written below it.
//         2. public/assets/brand/mark.svg: the mark built from the pack's loop and triangle paths, in the form the
//            app inlines to draw it on (layout.js).
// npm run tokens -- --check changes nothing and exits with code 1 if either file is out of date.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';

const root = join(dirname(new URL(import.meta.url).pathname), '..');
const t = JSON.parse(readFileSync(join(root, 'brand/ef-tokens.json'), 'utf8'));
const cssPath = join(root, 'public/assets/css/tokens.css');
const markPath = join(root, 'public/assets/brand/mark.svg');
const START = '/* tokens:start (generated by npm run tokens from brand/ef-tokens.json; do not edit between these 2 lines) */';
const END = '/* tokens:end */';

const { palette: p, themes: { light, inverted }, application: a, spacing, radius, motion, logo } = t;

// The 1 value where the app does not follow the pack. Pack 1.1 gives the light theme's primary button as slate.
// The primary button stays navy in both apps, and the designer is changing the pack to navy (decision of
// 11 November 2026). Remove this override once a pack arrives with navy as themes.light.primary.
const PRIMARY = { ground: p.navy.hex, ink: p.warmWhite.hex };

const lines = [
  `/* Brand pack ${t.version}, ${t.date} */`,
  ':root {',
  '  /* Palette: 4 colours and no others */',
  `  --sky: ${p.sky.hex};`,
  `  --slate: ${p.slate.hex};`,
  `  --navy: ${p.navy.hex};`,
  `  --warm-white: ${p.warmWhite.hex};`,
  '  /* The pack\'s own names for the same 4 colours (also the Client Hub\'s), so a component can be shared */',
  '  --ef-sky: var(--sky);',
  '  --ef-slate: var(--slate);',
  '  --ef-navy: var(--navy);',
  '  --ef-warm-white: var(--warm-white);',
  '',
  '  /* Light theme: the default everywhere in the app */',
  `  --ground: ${light.ground};`,
  `  --ink: ${light.ink};`,
  `  --panel: ${light.panel};`,
  `  --on-panel: ${light.onPanel};`,
  `  --reading-ground: ${light.readingGround};`,
  `  --on-reading: ${light.onReading};`,
  `  --hairline: ${light.hairline};`,
  `  --underline: ${light.underline};`,
  `  --focus: ${light.focus};`,
  `  /* Primary button: navy, not the pack's ${light.primary}. See PRIMARY in scripts/tokens.mjs. */`,
  `  --primary: ${PRIMARY.ground};`,
  `  --on-primary: ${PRIMARY.ink};`,
  '',
  '  /* Inverted theme: calls to action only. No dark mode in this release. */',
  `  --cta-ground: ${inverted.ground};`,
  `  --cta-ink: ${inverted.ink};`,
  `  --cta-panel: ${inverted.panel};`,
  `  --cta-on-panel: ${inverted.onPanel};`,
  `  --cta-hairline: ${inverted.hairline};`,
  `  --cta-underline: ${inverted.underline};`,
  `  --cta-focus: ${inverted.focus};`,
  '  --inv-ground: var(--cta-ground);',
  '  --inv-ink: var(--cta-ink);',
  '  --inv-panel: var(--cta-panel);',
  '  --inv-on-panel: var(--cta-on-panel);',
  '',
  '  /* Application colours: interface only (forms, messages, status), never on brand surfaces. Each colour is read',
  '     on its own tint or on warm white, and always with a word and an icon, never colour alone. */',
  `  --error: ${a.error.light};`,
  `  --error-tint: ${a.error.tint};`,
  `  --success: ${a.success.light};`,
  `  --success-tint: ${a.success.tint};`,
  `  --warning: ${a.warning.light};`,
  `  --warning-tint: ${a.warning.tint};`,
  `  --info: ${a.info.light};`,
  `  --info-tint: ${a.info.tint};`,
  '  /* Status: done is success, in progress is info, attention is warning */',
  `  --status-done: ${a.success.light};`,
  `  --status-done-tint: ${a.success.tint};`,
  `  --status-progress: ${a.info.light};`,
  `  --status-progress-tint: ${a.info.tint};`,
  `  --status-attention: ${a.warning.light};`,
  `  --status-attention-tint: ${a.warning.tint};`,
  '',
  '  /* Spacing scale */',
  ...spacing.map((v, i) => `  --space-${i + 1}: ${v}px;`),
  '',
  '  /* Radius. Surfaces are flat: no shadows. */',
  `  --radius-sm: ${radius.sm}px;`,
  `  --radius-md: ${radius.md}px;`,
  `  --radius-lg: ${radius.lg}px;`,
  `  --radius-pill: ${radius.pill}px;`,
  '',
  '  /* Motion */',
  `  --motion-duration: ${motion.durationMs}ms;`,
  `  --motion-ease: ${motion.easing};`,
  `  --mark-draw-duration: ${motion.markDrawOnMs}ms;`,
  '}',
];
const block = `${START}\n${lines.join('\n')}\n${END}`;

const css = readFileSync(cssPath, 'utf8');
const from = css.indexOf(START), to = css.indexOf(END);
if (from < 0 || to < 0) { console.error(`tokens.css has no "${START}" and "${END}" lines to write between.`); process.exit(1); }
const nextCss = css.slice(0, from) + block + css.slice(to + END.length);

// The mark for inlining: the standard drawing (a ${logo.mark.strokes.standard} unit stroke on the 100 grid). The loop carries
// pathLength="100" so it can be drawn on; the triangle is solid and fades in behind it. Colour is currentColor.
const m = logo.mark;
const nextMark = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${m.grid} ${m.grid}" role="img" aria-label="${t.brand}">
  <!-- Generated by npm run tokens from brand/ef-tokens.json (brand pack ${t.version}). Do not edit: change the token file. -->
  <path data-draw="1" pathLength="100" d="${m.loop.path}" fill="none" stroke="currentColor" stroke-width="${m.strokes.standard}" stroke-linecap="round" stroke-linejoin="round"/>
  <path data-fade="1" d="${m.triangle}" fill="currentColor"/>
</svg>
`;

const check = process.argv.includes('--check');
let stale = 0;
for (const [path, next, name] of [[cssPath, nextCss, 'public/assets/css/tokens.css'], [markPath, nextMark, 'public/assets/brand/mark.svg']]) {
  let now = '';
  try { now = readFileSync(path, 'utf8'); } catch (e) { /* not there yet */ }
  if (now === next) { console.log(`up to date  ${name}`); continue; }
  stale += 1;
  if (check) console.log(`OUT OF DATE ${name}`);
  else { writeFileSync(path, next); console.log(`written     ${name}`); }
}
if (check && stale) { console.error('\nRun npm run tokens.'); process.exit(1); }
